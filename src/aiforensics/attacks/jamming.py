def _strip_preamble(text: str) -> str:
    """Drop chat scaffolding an instruct model adds around the blocker text."""
    text = re.sub(r"^\s*(text|corpus|passage|answer)\s*:\s*", "", text.strip(), flags=re.I)
    return " ".join(text.strip().strip('"').strip().split())


def generate_oracle_texts(
    model: Any,
    tokenizer: Any,
    question: str,
    config: JammingConfig | None = None,
    *,
    verify_fn: Callable[[str], str] | None = None,
) -> list[str]:
    """Craft the oracle-generated jamming bodies ``d_j`` (paper §5.4).

    Prompt is :data:`ORACLE_PROMPT`, verbatim. The paper regenerates up to
    ``T = max_trials`` times, validating each draft by checking that it actually
    induces the refusal; the last draft is kept if the budget runs out, matching
    how the same loop is written in our PoisonedRAG implementation.

    **Deviation:** the paper's oracle is GPT-4-Turbo. This runs whatever local
    model is passed, Qwen3-1.7B by default in this testbed. The paper's
    GPT-4 → Claude-3-Opus swap halves jamming, so a 1.7B oracle should be
    expected to do worse still. The failure is usually visible in the text: a
    small model tends to answer the question instead of writing a passage that
    makes the question unanswerable.

    Args:
        model: Oracle causal LM.
        tokenizer: Its tokenizer.
        question: Target query.
        config: Hyperparameters.
        verify_fn: ``verify_fn(candidate_body) -> rag_response``. Supply a
            closure that puts the candidate in front of the *target* generator
            and returns its answer; a draft is accepted when that answer trips
            :func:`jamming_success`. ``None`` skips validation entirely, which
            is ``T = 1`` and strictly weaker.

    Returns:
        ``config.n_blocker`` jamming bodies, **without** the retrieval prefix.
        Pass them to :func:`craft_oracle` to get full blocker documents.
    """
    from ..models.llm import generate

    cfg = config or JammingConfig()
    prompt = ORACLE_PROMPT.format(
        question=question, target=cfg.target_text, words=cfg.words
    )

    texts: list[str] = []
    for slot in range(cfg.n_blocker):
        chosen = ""
        trials = max(1, cfg.max_trials) if verify_fn is not None else 1
        for trial in range(trials):
            out = generate(
                model, tokenizer, [prompt],
                max_new_tokens=max(64, cfg.words * 4),
                do_sample=True, temperature=cfg.temperature, top_p=0.95,
            )
            candidate = _strip_preamble(out[0])
            if not candidate:
                continue
            chosen = candidate
            if verify_fn is None or jamming_success(verify_fn(candidate)):
                break
            logger.debug(
                "slot %d trial %d: refusal not induced, regenerating", slot, trial
            )
        if not chosen:
            logger.warning(
                "oracle produced no usable text for %r after %d trials", question, trials
            )
        texts.append(chosen)
    return texts


def craft_oracle(question: str, jam_texts: Sequence[str]) -> list[str]:
    """Attach the retrieval prefix to oracle-generated bodies.

    ``d = question + ". " + d_j`` — the reference's
    ``cur_query_txt + ". " + cur_adv_doc_txt``, space included.

    Args:
        question: Target query.
        jam_texts: Output of :func:`generate_oracle_texts`.

    Returns:
        One blocker document per body.
    """
    return [question + _RETRIEVAL_JOIN + text for text in jam_texts]


